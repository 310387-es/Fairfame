-- Removing the sample workspace (11 Aug 2026).
--
-- "Explore with sample data" and everything behind it is gone: the CTA under
-- the create-organization form, the seeding, the banner, and the two actions
-- that made and deleted the demo. This drops the column that flagged it.
--
-- **The delete comes before the drop, and the order is the whole point.**
-- `is_sample` is the only thing that distinguished a demo café from a real
-- business. Drop the column while a flagged row still exists and that workspace
-- does not disappear — it becomes *indistinguishable from a real one*: a
-- workspace full of invented reviews, with the banner that said so now deleted,
-- sitting in the switcher beside the customer's actual business. The product's
-- own rule is that it never shows a number it cannot stand behind, and that
-- would be a whole workspace of them.
--
-- So the flagged organizations are removed while the flag can still identify
-- them. Nothing real is lost by definition: every row in one was generated by
-- `fillSampleWorkspace`, and the demo existed to be thrown away. The cascade on
-- `organizations` takes the reviews, the connection, the digests and the
-- membership with it — the same cascade `deleteSampleWorkspaceAction` relied on.
--
-- This is destructive and says so. It is also a no-op on every database it will
-- ever run against today: the feature never shipped past this repo, and
-- `SELECT count(*) FROM organizations WHERE is_sample` is 0 here. The statement
-- is written for the case where that is not true rather than left out because
-- it probably is.
--
-- A person left holding *only* a sample workspace ends up with no organization
-- and is redirected to `/create-organization` by the app shell, which is the
-- correct place for somebody who has no business set up yet.
DELETE FROM "organizations" WHERE "is_sample" = true;--> statement-breakpoint

ALTER TABLE "organizations" DROP COLUMN "is_sample";
